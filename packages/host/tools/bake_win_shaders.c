// bake_win_shaders <dir of .cso> <out .h>: the Windows host's compiled shaders (win_render.cpp's kept bytecode, one
// <key>.cso each, as a run with MBUI_SHADERS=<dir> leaves them) written as native/win_shaders_baked.h, so a program
// finds them in itself and compiles none as it starts (D3DCompile + D3DReflect of the glass shaders: ~4 s on a first
// start). A key no longer made by the sources (a shader changed) is simply never asked for: what is not baked is
// compiled and kept as before. Build with any C compiler: cc -O2 bake_win_shaders.c -o bake_win_shaders
#include <dirent.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int main(int argc, char **argv) {
  if (argc != 3) {
    fprintf(stderr, "usage: bake_win_shaders <dir> <out.h>\n");
    return 2;
  }
  DIR *d = opendir(argv[1]);
  if (!d) {
    perror(argv[1]);
    return 1;
  }
  char *names[256];
  int n = 0;
  struct dirent *e;
  while ((e = readdir(d)) && n < 256) {
    size_t l = strlen(e->d_name);
    if (l == 20 && !strcmp(e->d_name + 16, ".cso")) names[n++] = strdup(e->d_name);
  }
  closedir(d);
  for (int i = 0; i < n; i++)
    for (int j = i + 1; j < n; j++)
      if (strcmp(names[i], names[j]) > 0) {
        char *t = names[i];
        names[i] = names[j];
        names[j] = t;
      }
  FILE *o = fopen(argv[2], "w");
  if (!o) {
    perror(argv[2]);
    return 1;
  }
  fprintf(o, "// Generated by tools/bake_win_shaders.c from a run's kept shaders: do not edit. win_render.cpp's compile()\n");
  fprintf(o, "// takes a shader from here by its key before compiling it.\n#pragma once\n\n");
  int baked = 0;
  for (int i = 0; i < n; i++) {
    char path[4096];
    snprintf(path, sizeof path, "%s/%s", argv[1], names[i]);
    FILE *f = fopen(path, "rb");
    if (!f) continue;
    unsigned char head[16];
    if (fread(head, 1, 16, f) != 16 || memcmp(head, "MBSH", 4) != 0) {
      fclose(f);
      continue;
    }
    uint32_t size = (uint32_t)head[4] | (uint32_t)head[5] << 8 | (uint32_t)head[6] << 16 | (uint32_t)head[7] << 24;
    unsigned char *code = (unsigned char *)malloc(size);
    if (!code || fread(code, 1, size, f) != size) {
      fclose(f);
      free(code);
      continue;
    }
    fclose(f);
    fprintf(o, "static const unsigned char baked_shader_%d[%u] = {", baked, size);
    for (uint32_t k = 0; k < size; k++) fprintf(o, "%s%u,", k % 24 ? "" : "\n  ", code[k]);
    fprintf(o, "\n};\n");
    free(code);
    names[baked] = names[i];
    baked++;
  }
  fprintf(o, "\nstatic const struct {\n  unsigned long long key;\n  unsigned size;\n  const unsigned char *code;\n} baked_shaders[] = {\n");
  for (int i = 0; i < baked; i++)
    fprintf(o, "  {0x%.16sULL, sizeof baked_shader_%d, baked_shader_%d},\n", names[i], i, i);
  fprintf(o, "  {0, 0, 0},\n};\n");
  fclose(o);
  fprintf(stderr, "bake_win_shaders: %d shaders -> %s\n", baked, argv[2]);
  return 0;
}
