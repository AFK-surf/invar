"""Compile the monochrome SVG masters. Run with uv run scripts/gen_icons.py."""
import argparse
import json
import math
import xml.etree.ElementTree as ET
from pathlib import Path

from fontTools.misc.bezierTools import splitCubicAtT
from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parents[1]
SVG = "{http://www.w3.org/2000/svg}"
TOLERANCE = 0.025  # maximum control-point distance from the chord, in grid units


def distance_to_segment(point, start, end):
    a, b, p = (complex(*xy) for xy in (start, end, point))
    chord = b - a
    if not chord:
        return abs(p - a)
    t = max(0, min(1, ((p - a) / chord).real))
    return abs(p - (a + t * chord))


class OutlinePen(BasePen):
    """Parse SVG arcs and quadratics as cubics, then adaptively flatten them."""

    def __init__(self):
        super().__init__(None)
        self.outlines = []
        self.points = []

    def _moveTo(self, point):
        self.points = []
        self._lineTo(point)

    def _lineTo(self, point):
        point = tuple(round(v, 4) for v in point)
        if not self.points or point != self.points[-1]:
            self.points.append(point)

    def _curveToOne(self, p1, p2, p3):
        def flatten(a, b, c, d):
            if max(distance_to_segment(p, a, d) for p in (b, c)) <= TOLERANCE:
                self._lineTo(d)
            else:
                for half in splitCubicAtT(a, b, c, d, 0.5):
                    flatten(*half)

        flatten(self._getCurrentPoint(), p1, p2, p3)

    def finish(self, closed):
        if closed and self.points[-1] == self.points[0]:
            self.points.pop()
        if len(self.points) < (3 if closed else 2):
            raise ValueError("degenerate contour")
        self.outlines.append((self.points, closed))
        self.points = []

    def _closePath(self):
        self.finish(True)

    def _endPath(self):
        self.finish(False)


def read_layers(file):
    root = ET.parse(file).getroot()
    if root.tag != SVG + "svg" or root.get("viewBox") != "0 0 24 24":
        raise ValueError("expected a 24-unit SVG")
    attrs = {"fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "fill-rule"}
    if root.attrib.keys() - attrs - {"viewBox", "width", "height"}:
        raise ValueError("unsupported SVG root attribute")
    for path in root:
        if path.tag != SVG + "path" or path.attrib.keys() - attrs - {"d"}:
            raise ValueError("use untransformed SVG paths")
        style = root.attrib | path.attrib
        fill, stroke = style.get("fill"), style.get("stroke")
        rule = style.get("fill-rule", "nonzero")
        if rule not in ("nonzero", "evenodd") or any(v not in ("none", "currentColor") for v in (fill, stroke)):
            raise ValueError("expected monochrome path")
        if stroke != "none" and (style.get("stroke-width"), style.get("stroke-linecap"), style.get("stroke-linejoin")) != ("1.75", "round", "round"):
            raise ValueError("expected the regular round stroke")
        pen = OutlinePen()
        parse_path(path.attrib["d"], pen)
        for points, closed in pen.outlines:
            if fill != "none" and not closed:
                raise ValueError("close filled contours explicitly")
            pad = 1.125 if stroke != "none" else 0.0  # widest optical weight
            if any(not math.isfinite(v) or not 2 + pad <= v <= 22 - pad for p in points for v in p):
                raise ValueError("ink exceeds the two-unit inset")
        if not pen.outlines or fill == stroke == "none":
            raise ValueError("empty layer")
        yield pen.outlines, fill != "none", stroke != "none", rule == "evenodd"


def generate():
    files = sorted((ROOT / "svg").glob("*.svg"))
    lines = [
        "// Generated by scripts/gen_icons.py from svg/*.svg.",
        'import "paint"', "",
        "pub fn icon_names() -> Array[String] {", "  [",
        *[f'    {json.dumps(f.stem)},' for f in files],
        "  ]", "}", "",
        "fn draw_icon(name : String, scale : Double, ink : Int64, width : Double) -> Array[paint::Shape] {",
        "  match name {",
    ]
    for file in files:
        lines.append(f'    "{file.stem}" => [')
        try:
            for outlines, fill, stroke, even_odd in read_layers(file):
                lines.append("      paint::shape_of([")
                for points, closed in outlines:
                    values = [str(float(v)) for pair in points for v in pair]
                    lines.append("        (scaled([")
                    for i in range(0, len(values), 10):
                        lines.append("          " + ", ".join(values[i:i + 10]) + ",")
                    lines.append(f"        ], scale), {str(closed).lower()}),")
                params = []
                if fill:
                    params.append("fill=ink")
                    if even_odd:
                        params.append("even_odd=true")
                if stroke:
                    params.extend(("stroke=ink", "width=width"))
                lines.append("      ], " + ", ".join(params) + "),")
        except ValueError as error:
            raise ValueError(f"{file.name}: {error}") from error
        lines.append("    ]")
    return "\n".join(lines + ["    _ => []", "  }", "}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated data is stale")
    args = parser.parse_args()
    target = ROOT / "src/data.pion"
    result = generate()
    if args.check:
        if result != target.read_text():
            raise SystemExit("regenerate src/data.pion")
    else:
        target.write_text(result)
